#Python Assignment Operators

a=10
print("Initial value of a=",a)

#Addition Assignment
a+=4
print("a+=4:",a)

#Subtraction Assignment
a-=7
print("a-=7:",a)

#Multiplication Assignment
a*=6
print("a*=6:",a)

#Division Assignment
a/=9
print("a/9:",a)

#Modulus Assignment
a%=2
print("a%=2:",a)

#Exponent Assignment
a=5
a**=2
print("a**=2:",a)

#Floor Division Assignment
a=6
a//=8
print("a//=8:",a)

#Bitwise AND Assignment
a=10
a&=2
print("a&=2:",a)

#Bitwise OR Assignment
a=10
a|=9
print("a|=9:",a)

#Bitwise XOR Assignment
a=10
a^=6
print("a^=6:",a)

#Left Shift Assignment
a=10
a<<=7
print("a<<=7:",a)

#Right shift Assignment
a=10
a>>=9
print("a>>=9:",a)